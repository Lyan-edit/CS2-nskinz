"""Project model-authored keychain regions onto the sticker preview camera."""

import argparse
import hashlib
import json
from pathlib import Path
import re
import struct
import subprocess
import tempfile

import numpy as np

from generate_sticker_preview_projection import collect_mesh, cpp_float, make_projector


def read_markup(resource, viewer, directory):
    data = resource.read_bytes()
    offset, count = struct.unpack_from("<II", data, 8)
    for index in range(count):
        entry = 8 + offset + 12 * index
        name, relative, size = struct.unpack_from("<4sII", data, entry)
        if name == b"DATA":
            start = entry + 4 + relative
            block = data[start:start + size]
            if len(block) != size:
                raise ValueError(f"{resource}: truncated DATA block")
            break
    else:
        raise ValueError(f"{resource}: missing DATA block")
    isolated = directory / resource.name
    isolated.write_bytes(struct.pack("<IHHII4sII", 28 + size, 12, 1, 8, 1, b"DATA", 8, size) + block)
    text = subprocess.check_output([str(viewer), "-i", str(isolated), "-b", "DATA"], encoding="utf-8")
    section = re.search(r"\bKeychainMarkup\s*=\s*\[(.*?)\n\t\]", text, re.S)
    if not section:
        raise ValueError(f"{resource}: missing KeychainMarkup")
    result = {False: [], True: []}
    for entry in re.findall(r"\{([^{}]*)\}", section[1], re.S):
        legacy = bool(re.search(r"LegacyModel\s*=\s*true", entry))
        bone = re.search(r'BoneName\s*=\s*"([^"]+)"', entry)[1]
        corners = re.search(r"Corners\s*=\s*\[(.*?)\]", entry, re.S)[1]
        points = np.asarray([float(value) for value in corners.replace(",", " ").split()]).reshape(4, 3)
        result[legacy].append((bone, points))
    return result


def gltf_points(points):
    # Source 2 Viewer converts Source inches and axes to glTF metres.
    return points[..., [1, 2, 0]] * 0.0254


def components(values):
    return "{" + ", ".join(cpp_float(value) for value in values) + "}"


def generate(models, resources, viewer, temporary, defaults):
    triangles, layouts = [], []
    for key, variants in defaults.items():
        definition = int(key)
        resource = resources / f"{definition}.vmdl_c"
        if hashlib.sha256(resource.read_bytes()).hexdigest() != variants["sha256"]:
            raise ValueError(f"{resource}: default mount table and model resource differ")
        regions = read_markup(resource, viewer, temporary)
        gltf = models / f"{definition}.gltf"
        document = json.loads(gltf.read_text(encoding="utf-8"))
        blob = gltf.with_suffix(".bin").read_bytes()
        for legacy in (False, True):
            mount = variants.get("legacy" if legacy else "modern") or variants.get("modern") or variants["legacy"]
            _, mesh_positions = collect_mesh(document, blob, legacy)
            project = make_projector(mesh_positions, include_depth=True)
            anchor, _ = project(gltf_points(np.asarray([mount["position"]])))
            start = len(triangles)
            candidates = regions[legacy] or regions[not legacy]
            for bone, points in candidates:
                # The serialized slot uses the same attachment bone as the
                # default mount. Regions belonging to other bones are excluded.
                if bone != mount["bone"]:
                    continue
                projected, depth = project(gltf_points(points))
                centered = projected - projected.mean(axis=0)
                order = np.argsort(np.arctan2(centered[:, 1], centered[:, 0]))
                for indices in (order[[0, 1, 2]], order[[0, 2, 3]]):
                    a, b, c = projected[indices]
                    if abs(np.linalg.det(np.array([b - a, c - a]))) < 1e-8:
                        continue
                    screen = ", ".join(components(point) for point in projected[indices])
                    coords = ", ".join(components(point) for point in points[indices])
                    triangles.append(f"    {{{{{screen}}}, {{{coords}}}, {components(depth[indices])}}},")
            if len(triangles) == start or not np.all((anchor >= 0) & (anchor <= 1)):
                raise ValueError(f"{resource}: unusable mount projection (legacy={legacy})")
            layouts.append(f"    {{{definition}, {str(legacy).lower()}, {components(anchor[0])}, {start}, {len(triangles) - start}}},")
    return "\n".join([
        "#pragma once",
        '// Generated by tools/generate_keychain_preview.py.',
        '#include "UI/StickerPreviewPlacement.generated.hpp"',
        "",
        "namespace nskinzcs2::ui::keychain_preview",
        "{",
        "using sticker_preview::PreviewPoint;",
        "struct MountTriangle { PreviewPoint screen[3]; float position[3][3]; float inverse_depth[3]; };",
        "struct MountLayout { int definition; bool legacy; PreviewPoint anchor; std::size_t first, count; };",
        f"inline constexpr std::array<MountTriangle, {len(triangles)}> kMountTriangles {{{{",
        *triangles,
        "}};",
        f"inline constexpr std::array<MountLayout, {len(layouts)}> kMountLayouts {{{{",
        *layouts,
        "}};",
        "}",
        "",
    ])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--models", type=Path, required=True)
    parser.add_argument("--resources", type=Path, required=True)
    parser.add_argument("--viewer", type=Path, required=True)
    parser.add_argument("--output", type=Path, default=Path("src/UI/KeychainPreview.generated.hpp"))
    args = parser.parse_args()
    defaults = json.loads(Path("tools/nskinz-demo-rewriter/src/keychain_mounts.json").read_text(encoding="utf-8"))
    with tempfile.TemporaryDirectory(prefix="keychain-preview-", dir="build") as directory:
        header = generate(args.models, args.resources, args.viewer.resolve(), Path(directory), defaults)
    args.output.write_text(header, encoding="utf-8")


if __name__ == "__main__":
    main()
