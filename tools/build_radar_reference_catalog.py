"""Validate and embed reviewed Workshop radar PNGs, matched to exact source textures."""
from __future__ import annotations

import argparse
import csv
import hashlib
import json
from pathlib import Path
import re
import shutil
from datetime import date

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'assets/radar_references'
MANIFEST = ASSETS / 'catalog.json'
HEADER = ROOT / 'src/Runtime/RadarReferenceCatalog.generated.hpp'
RESOURCE = ROOT / 'src/Resources/RadarReferenceCatalog.generated.rc2'


def fnv(data: bytes) -> int:
    value = 14695981039346656037
    for byte in data:
        value = ((value ^ byte) * 1099511628211) & 0xffffffffffffffff
    return value


def inspect_png(path: Path) -> dict:
    with Image.open(path) as image:
        if image.mode != 'RGBA':
            raise ValueError(f'{path}: RGBA required')
        width, height = image.size
        histogram = image.getchannel('A').histogram()
    if not 64 <= width <= 4096 or not 64 <= height <= 4096:
        raise ValueError(f'{path}: unexpected radar dimensions')
    if not histogram[0] or sum(histogram[1:]) < width * height // 100:
        raise ValueError(f'{path}: transparent background and map foreground required')
    return dict(width=width, height=height, transparent_pixels=histogram[0],
                visible_pixels=sum(histogram[1:]), sha256=hashlib.sha256(path.read_bytes()).hexdigest())


def import_reviewed(inventory: Path, candidates: Path) -> None:
    entries = []
    by_source = {}
    old = json.loads(MANIFEST.read_text(encoding='utf-8'))['references'] if MANIFEST.exists() else []
    locked = {entry['virtual_path']: entry for entry in old if entry.get('locked')}
    with inventory.open(encoding='utf-8', newline='') as inventory_file:
        inventory_rows = list(csv.DictReader(inventory_file, delimiter='\t'))
    for row in inventory_rows:
        source_key = (row['virtual_path'], row['source_fnv1a64'])
        if source_key in by_source:
            entry = by_source[source_key]
            entry['workshop_ids'] = sorted(set(entry['workshop_ids'] + [row['workshop']]))
            entry['map_names'] = sorted(set(entry['map_names'] + [row['map']]))
            continue
        candidate = candidates / (row['file'] + '.png')
        if not candidate.is_file():
            continue
        if row['virtual_path'] in locked:
            entry = locked[row['virtual_path']]
            if entry not in entries:
                entries.append(entry)
            by_source[source_key] = entry
            if row['source_fnv1a64'] == entry['source_fnv1a64'] and inspect_png(candidate)['sha256'] != entry['sha256']:
                raise ValueError(f"{entry['key']}: user-locked standard cannot be replaced by an import")
            continue
        raw = inventory.parent / (row['file'] + '.vtex_c')
        source = raw.read_bytes()
        if len(source) != int(row['source_size']) or fnv(source) != int(row['source_fnv1a64'], 16):
            raise ValueError(f'{raw}: source fingerprint mismatch')
        if not re.fullmatch(r'[A-Za-z0-9_-]+', row['map']):
            raise ValueError('unexpected map name')
        filename = row['map'] + '_' + row['source_fnv1a64'] + '.png'
        ASSETS.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(candidate, ASSETS / filename)
        entry = dict(key=row['map'] + '-' + row['source_fnv1a64'], file=filename,
                     virtual_path=row['virtual_path'], source_fnv1a64=row['source_fnv1a64'],
                     source_sha256=hashlib.sha256(source).hexdigest(), source_size=len(source),
                     workshop_ids=[row['workshop']], map_names=[row['map']],
                     review='source-outline-and-transparent-composite', reviewed_on=date.today().isoformat(),
                     **inspect_png(ASSETS / filename))
        entries.append(entry)
        by_source[source_key] = entry
    for entry in locked.values():
        if entry not in entries:
            entries.append(entry)
    entries.sort(key=lambda entry: (entry['virtual_path'], entry['source_fnv1a64']))
    MANIFEST.write_text(json.dumps(dict(version=1, references=entries), ensure_ascii=False, indent=2) + '\n', encoding='utf-8')


def generate() -> None:
    entries = json.loads(MANIFEST.read_text(encoding='utf-8'))['references']
    rows = []
    resources = ['// Generated by tools/build_radar_reference_catalog.py; do not edit.']
    seen = set()
    for index, entry in enumerate(entries):
        if not re.fullmatch(r'[A-Za-z0-9_-]+\.png', entry['file']):
            raise ValueError('reference asset path must be a simple PNG filename')
        actual = inspect_png(ASSETS / entry['file'])
        if any(entry[key] != value for key, value in actual.items()):
            raise ValueError(f"{entry['file']}: image changed; review and update its manifest")
        if not re.fullmatch(r'[0-9a-f]{1,16}', entry['source_fnv1a64']):
            raise ValueError('invalid source fingerprint')
        identity = (entry['virtual_path'].lower(), entry['source_fnv1a64'])
        if identity in seen or not entry.get('review'):
            raise ValueError('duplicate or unreviewed reference')
        seen.add(identity)
        resource = 400 + index
        rows.append('    {' + ', '.join([
            json.dumps(entry['virtual_path'].lower()), '0x' + entry['source_fnv1a64'] + 'ull',
            str(entry['source_size']), str(resource), str(entry['width']), str(entry['height']),
            json.dumps(entry['key']), 'true' if entry.get('locked') else 'false',
            str(entry['visible_pixels']), str(entry['transparent_pixels'])]) + '},')
        resources.append(f'{resource} RCDATA "../../assets/radar_references/{entry["file"]}"')
    text = '''// Generated by tools/build_radar_reference_catalog.py; do not edit.
#pragma once
#include <array>
#include <cstddef>
#include <cstdint>
#include <string_view>
namespace nskinzcs2::runtime
{
struct AuditedRadarReference
{
    std::string_view virtual_path;
    std::uint64_t source_hash;
    std::size_t source_size;
    int resource_id;
    std::uint16_t width, height;
    std::string_view key;
    bool locked;
    std::size_t visible_pixels, transparent_pixels;
};
inline constexpr std::array<AuditedRadarReference, COUNT> kAuditedRadarReferences {{
ROWS
}};
}
'''.replace('COUNT', str(len(rows))).replace('ROWS', '\n'.join(rows))
    HEADER.write_text(text, encoding='utf-8')
    RESOURCE.write_text('\n'.join(resources) + '\n', encoding='utf-8')
    print(f'validated {len(entries)} reviewed source versions; generated C++ and embedded resources')


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--import-reviewed', type=Path, metavar='INVENTORY_TSV')
    parser.add_argument('--candidates', type=Path)
    parser.add_argument('--confirm-reviewed', action='store_true', help='Confirm every imported candidate was visually reviewed')
    args = parser.parse_args()
    if args.import_reviewed:
        if not args.candidates or not args.confirm_reviewed:
            parser.error('import requires --candidates and explicit --confirm-reviewed')
        import_reviewed(args.import_reviewed, args.candidates)
    generate()


if __name__ == '__main__':
    main()
